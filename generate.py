def read(path: Path) -> str:
    if not path.is_file():
        raise BuildError(f"missing required file: {path.relative_to(REPO)}")
    return path.read_text(encoding="utf-8")


def human_size(nbytes: int) -> str:
    if nbytes < 1024:
        return f"{nbytes} B"
    if nbytes < 1024 * 1024:
        return f"{nbytes / 1024:.0f} KB"
    return f"{nbytes / (1024 * 1024):.1f} MB"


def png_size(path: Path) -> Tuple[int, int]:
    """Read width/height straight from the PNG IHDR chunk."""
    with path.open("rb") as fh:
        head = fh.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        raise BuildError(f"not a PNG: {path}")
    return struct.unpack(">II", head[16:24])


def slug(text: str) -> str:
    """Approximate kramdown's heading -> anchor conversion."""
    out = re.sub(r"[^\w\s-]", "", text.lower())
    return re.sub(r"[\s_]+", "-", out).strip("-")


def chip(colour: Optional[str]) -> str:
    if not colour:
        return '<span class="chip chip-none">not in model</span>'
    cls = colour.lower()
    return f'<span class="chip chip-{cls}">{html.escape(COLOUR_SHORT.get(colour, colour))}</span>'


def write_page(rel: str, front: Dict[str, object], body: str) -> Path:
    """Write a generated page with YAML frontmatter."""
    dest = PAGES / rel
    dest.parent.mkdir(parents=True, exist_ok=True)

    lines = ["---"]
    for key, value in front.items():
        if value is None:
            continue
        if isinstance(value, (int, float)):
            lines.append(f"{key}: {value}")
        else:
            lines.append(f'{key}: "{str(value)}"')
    lines.append("---")
    lines.append(BANNER)
    lines.append("")

    dest.write_text("\n".join(lines) + body.rstrip() + "\n", encoding="utf-8")
    return dest


